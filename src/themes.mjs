const lum = (hex) => {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
export const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m); return (x + 0.05) / (y + 0.05); };

const pairs = [["ink", "bg"], ["ink", "card"], ["muted", "bg"], ["muted", "card"], ["muted", "bg-2"], ["accent", "bg"], ["accent", "card"], ["accent-ink", "accent"], ["accent", "accent-soft"], ["ink", "bg-2"]];

export function check() {
  const fails = [];
  for (const [key, t] of Object.entries(themes))
    for (const mode of ["light", "dark"])
      for (const [fg, bg] of pairs) {
        const v = ratio(t[mode][fg], t[mode][bg]);
        if (v < 4.5) fails.push(`${key} ${mode}: ${fg} on ${bg} = ${v.toFixed(2)}`);
      }
  // the cream glyph on the logo tile is a graphic: 3:1 is the AA bar for non-text
  for (const [key, t] of Object.entries(themes)) {
    const v = Math.min(ratio("#fcf7ee", t.light.tile), ratio("#fcf7ee", t.dark.tile));
    if (v < 3) fails.push(`${key}: logo glyph on tile = ${v.toFixed(2)}`);
  }
  return fails;
}

const vars = (o) => Object.entries(o).map(([k, v]) => `--${k}: ${v};`).join(" ");
export function css() {
  let out = "/* Element themes, generated by src/themes.mjs */\n";
  for (const [key, t] of Object.entries(themes)) {
    out += `:root[data-el="${key}"] { ${vars(t.light)} color-scheme: light; }\n`;
    out += `@media (prefers-color-scheme: dark) { :root[data-el="${key}"]:not([data-theme="light"]) { ${vars(t.dark)} color-scheme: dark; } }\n`;
    out += `:root[data-el="${key}"][data-theme="dark"] { ${vars(t.dark)} color-scheme: dark; }\n`;
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const fails = check();
  console.log(fails.length ? "AA FAILS:\n" + fails.join("\n") : `AA OK: ${Object.keys(themes).length * 2} palettes, ${pairs.length} text pairs each, logo tile 3:1`);
}
